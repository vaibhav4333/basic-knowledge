operator = input("enter the operator (+, -, *, /):")
n1 = int(input("enter the 1st number:"))
n2 = int(input("enter the 2nd number:"))

if operator == "+":
    print(n1+n2)
elif operator == "-":
    print(n1-n2)
elif operator =="*":
    print(n1*n2)
elif operator == "/":
    print(n1/n2)
